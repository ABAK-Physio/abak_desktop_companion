import 'dart:io';
import 'dart:convert';
import 'package:flutter_test/flutter_test.dart';
import 'package:xml/xml.dart';
import 'package:abak_desktop_companion/features/patients/services/dmp_chain/native/td31_submission.dart';
import 'package:abak_desktop_companion/features/patients/services/dmp_chain/native/td31a.dart';
import 'package:abak_desktop_companion/features/patients/services/dmp_chain/contracts.dart';
import 'package:abak_desktop_companion/features/patients/services/document_medical_service.dart';

void main() {
  final archive = Platform.environment['DV1_CONS_SUB_ARCHIVE'];
  test(
    'read-only archive replay: 34 documents and 27 proven lot signatures',
    () async {
      final root = Directory(archive!);
      final files = {
        for (final f in root.listSync().whereType<File>())
          f.path: f.readAsBytesSync(),
      };
      String read(String name) => utf8.decode(files['${root.path}/$name']!);
      final saved = jsonDecode(read('result.json'));
      final record = Map<String, dynamic>.from(saved['record']);
      expect(medicalHash(record), saved['sha256']);
      var index = 0;
      const wsa = 'http://www.w3.org/2005/08/addressing';
      const rim = 'urn:oasis:names:tc:ebxml-regrep:xsd:rim:3.0';
      Map<String, String> slots(String xml) => {
        for (final e in XmlDocument.parse(
          xml,
        ).findAllElements('Slot', namespace: rim))
          e.getAttribute('name')!: e.innerText,
      };
      final result = await DmpSubmissionSearch().run(
        envelope: read('td31sub-1-submissions-request.xml'),
        ins: '148115530271002',
        period: Dv1SubmissionPeriod.days('2026-04-01', '2026-04-30'),
        exchange: (stage, request) async {
          final item = (record['submissionExchanges'] as List)[index++];
          expect(stage, item['stage']);
          final prefix = item['files'];
          final sent = read('$prefix-request.xml');
          final response = read('$prefix-response.xml');
          final headers = read('$prefix-http.txt');
          expect(medicalHash(sent), item['requestHash']);
          expect(medicalHash(response), item['responseHash']);
          // Validate the original, untouched correlation before rebasing in memory
          // for the new UUID generated by the offline workflow. No file is written.
          DmpNativeTd31a.registryObjects(
            sent,
            DmpTd02Reply(item['httpStatus'], response, headers: headers),
          );
          expect(slots(request), slots(sent));
          final doc = XmlDocument.parse(response);
          doc
              .findAllElements('RelatesTo', namespace: wsa)
              .single
              .innerText = XmlDocument.parse(
            request,
          ).findAllElements('MessageID', namespace: wsa).single.innerText;
          return DmpTd02Reply(
            item['httpStatus'],
            doc.toXmlString(),
            headers: headers,
          );
        },
      );
      expect(index, 3);
      expect(result['documents'], hasLength(34));
      expect(result['submissionSets'], hasLength(35));
      expect(result['omittedSignatureIds'], hasLength(27));
      expect(result['unreturnedDocumentIds'], isEmpty);
      expect(
        (result['omittedSignatureIds'] as List).toSet(),
        (record['unreturnedDocumentIds'] as List).toSet(),
      );
      expect(record['state'], 'submission_search_incomplete');
      for (final e in files.entries) {
        expect(File(e.key).readAsBytesSync(), e.value);
      }
    },
    skip: archive == null ? 'Opt-in archived data; no network/CPS.' : false,
  );
}
